        [InlineData("abc123", "abc123")]
        [InlineData("f7e1a0c2-3b4d-4e5f-8a9b-0c1d2e3f4a5b", "f7e1a0c2-3b4d-4e5f-8a9b-0c1d2e3f4a5b")]
        [InlineData("a b/c:d?e*f", "a-b-c-d-e-f")]
        [InlineData("", "s")]
        [InlineData("...", "s")]
        [InlineData("name.lock", "name-lock")]
        public void SanitizeRefPart_ProducesValidRefComponents(string input, string expected) =>
            Assert.Equal(expected, GitCheckpointService.SanitizeRefPart(input));
    }
